import os
import time
import modal

# Define the Modal App name
app = modal.App("gemma-2-2b-vllm")

# Build a container image with CUDA-compatible vLLM and Hugging Face Transfer client
vllm_image = (
    modal.Image.debian_slim(python_version="3.11")
    .pip_install(
        "vllm==0.5.4",
        "openai>=1.0.0",
        "hf-transfer>=0.1.6"
    )
    .env({
        "HF_HUB_ENABLE_HF_TRANSFER": "1",
        # Ensure fast-downloading is prioritized
    })
)

# Host the model on an NVIDIA L4 GPU (24GB VRAM)
# We use @modal.web_server which wraps the vLLM OpenAI-compatible server
@app.function(
    gpu="L4",
    image=vllm_image,
    timeout=1800,
    # We mount the Hugging Face token secret so we can download gated model weights (if required)
    secrets=[modal.Secret.from_name("huggingface", required=False)]
)
@modal.web_server(port=8000, startup_timeout=300)
def entrypoint():
    """
    Spawns the official vLLM OpenAI-compatible API server in a background subprocess.
    Modal handles the routing of external public requests directly to port 8000.
    """
    import subprocess
    
    print("Starting vLLM OpenAI API Server with google/gemma-2-2b-it...")
    cmd = [
        "python", "-m", "vllm.entrypoints.openai.api_server",
        "--model", "google/gemma-2-2b-it",
        "--port", "8000",
        "--host", "0.0.0.0",
        "--gpu-memory-utilization", "0.90",
        "--max-model-len", "4096"
    ]
    
    # Launch vLLM server in background. Modal's @web_server will poll port 8000
    # until it is healthy before directing public traffic to it.
    process = subprocess.Popen(cmd)
    return process


