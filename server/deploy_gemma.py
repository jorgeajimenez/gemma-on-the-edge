# MINIMAL CLIENT TEST SNIPPET
# =====================================================================
# This code runs on your local machine when executing: `modal run deploy_gemma.py`

@app.local_entrypoint()
def test_client():
    """
    Local entrypoint to test the deployed vLLM engine.
    This script is invoked locally, triggers the remote server deployment,
    and streams a response from the public URL.
    """
    from openai import OpenAI
    
    # Obtain the secure public URL generated by Modal for our web server
    server_url = entrypoint.web_url
    print(f"\n[INFO] vLLM Cloud Gateway successfully deployed!")
    print(f"[INFO] API Endpoint: {server_url}/v1")
    
    print("\n[INFO] Initializing test client connection...")
    client = OpenAI(
        base_url=f"{server_url}/v1",
        api_key="any-string-works-locally" # vLLM doesn't require a key by default
    )
    
    prompt = "Explain the difference between local edge inference and cloud GPU cluster inference."
    print(f"\n[PROMPT] {prompt}\n")
    print("[RESPONSE] ", end="", flush=True)
    
    try:
        completion_stream = client.chat.completions.create(
            model="google/gemma-2-2b-it",
            messages=[
                {"role": "user", "content": prompt}
            ],
            stream=True,
            temperature=0.7,
            max_tokens=256
        )
        
        for chunk in completion_stream:
            content = chunk.choices[0].delta.content
            if content:
                print(content, end="", flush=True)
        print("\n")
        
    except Exception as e:
        print(f"\n[ERROR] Request failed: {e}")
        print("\nMake sure your Hugging Face credentials are set in Modal if 'google/gemma-2-2b-it' requires gated access acceptance.")
